    public void mostrarPortada(String titulo, String tema, String autor) {
        lblTitulo.setText(titulo);
        lblTema.setText(tema);
        lblAutor.setText(autor);
    }

    //muestra una linea del indice del libro 
    public void mostrarIndice(int numero, String texto) {
        switch (numero) {
            case 1:
                lblPagina1.setText(texto);
                break;
            case 2:
                lblPagina2.setText(texto);
                break;
            case 3:
                lblPagina3.setText(texto);
                break;
            case 4:
                lblPagina4.setText(texto);
                break;
        }
    }

